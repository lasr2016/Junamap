-- ------------------------------------------------------------------------------
-- 1. CREACIÓN DE LA TABLA 'locales'
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.locales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID único incremental
    nombre VARCHAR(150) NOT NULL,                           -- Nombre (admite sucursales/duplicados)
    tipo VARCHAR(50) NOT NULL,                              -- 'Almuerzo', 'Cafetería', 'Minimarket', 'Panadería'
    direccion TEXT NOT NULL,                                -- Dirección física
    lat DOUBLE PRECISION NOT NULL,                          -- Coordenada Latitud
    lng DOUBLE PRECISION NOT NULL,                          -- Coordenada Longitud
    abre TIME,                                              -- Hora apertura (formato TIME 'HH:MM:SS')
    cierra TIME,                                            -- Hora cierre (formato TIME 'HH:MM:SS')
    telefono VARCHAR(30),                                   -- Teléfono de contacto
    descripcion TEXT,                                       -- Detalle de la oferta gastronómica
    verificado BOOLEAN DEFAULT FALSE,                       -- Estado verificado con tarjeta BAES
    metodo_cobro VARCHAR(100) DEFAULT 'Edenred POS',        -- Método de cobro aceptado
    productos TEXT[] DEFAULT '{}',                          -- Array de etiquetas/productos para búsqueda
    activo BOOLEAN DEFAULT TRUE,                            -- Visibilidad en el mapa
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Índices para optimizar consultas, búsquedas y filtros en el mapa
CREATE INDEX IF NOT EXISTS idx_locales_tipo ON public.locales(tipo);
CREATE INDEX IF NOT EXISTS idx_locales_activo ON public.locales(activo);
CREATE INDEX IF NOT EXISTS idx_locales_productos ON public.locales USING GIN(productos);

-- ------------------------------------------------------------------------------
-- 2. PERMISOS Y SEGURIDAD (ROW LEVEL SECURITY - RLS)
-- Evita el error 401 Unauthorized y 'permission denied'
-- ------------------------------------------------------------------------------
-- Conceder permisos de lectura a la API pública (anon) y usuarios autenticados
GRANT SELECT ON public.locales TO anon, authenticated;

-- Activar RLS
ALTER TABLE public.locales ENABLE ROW LEVEL SECURITY;

-- Política de lectura: cualquier visitante puede ver los locales con activo = true
DROP POLICY IF EXISTS "Lectura publica de locales activos" ON public.locales;

CREATE POLICY "Lectura publica de locales activos" 
ON public.locales 
FOR SELECT 
TO anon, authenticated 
USING (activo = true);

