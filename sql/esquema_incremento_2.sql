-- 6. TABLA INTERMEDIA LOCALES_PRODUCTOS (N:M)
CREATE TABLE IF NOT EXISTS public.locales_productos (
    local_id BIGINT REFERENCES public.locales(id) ON DELETE CASCADE,
    producto_id BIGINT REFERENCES public.productos(id) ON DELETE CASCADE,
    disponible BOOLEAN DEFAULT TRUE,
    PRIMARY KEY (local_id, producto_id)
);

-- 7. TABLA DE AUDITORÍA: VERIFICAR_LOCALES
CREATE TABLE IF NOT EXISTS public.verificar_locales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id BIGINT REFERENCES public.locales(id) ON DELETE CASCADE,
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30),
    admin_nombre VARCHAR(100) DEFAULT 'Admin',
    fecha TIMESTAMPTZ DEFAULT NOW()
);

-- 8. VISTA OPTIMIZADA PARA RENDIMIENTO MÓVIL (< 200ms)
CREATE OR REPLACE VIEW public.vista_locales_mapa AS
SELECT 
    l.id,
    l.nombre,
    COALESCE(c.nombre, l.tipo, 'Almuerzo') AS tipo,
    COALESCE(c.color_hex, '#d8502c') AS color_hex,
    l.direccion,
    COALESCE(l.comuna, 'Talca') AS comuna,
    COALESCE(l.latitud, l.lat) AS lat,
    COALESCE(l.longitud, l.lng) AS lng,
    l.abre,
    l.cierra,
    l.telefono,
    l.descripcion,
    l.metodo_cobro,
    COALESCE(l.estado, 'verificado') AS estado,
    l.verificado_por,
    l.ultima_verificacion,
    l.activo,
    COALESCE(
        ARRAY_AGG(p.nombre) FILTER (WHERE p.nombre IS NOT NULL), 
        l.productos,
        '{}'
    ) AS productos
FROM public.locales l
LEFT JOIN public.categorias c ON l.categoria_id = c.id
LEFT JOIN public.locales_productos lp ON l.id = lp.local_id
LEFT JOIN public.productos p ON lp.producto_id = p.id
WHERE (l.estado = 'verificado' OR l.verificado = true) AND l.activo = true
GROUP BY l.id, c.nombre, c.color_hex;

-- 9. PERMISOS Y POLÍTICAS RLS
GRANT SELECT ON public.usuarios TO anon, authenticated;
GRANT SELECT ON public.categorias TO anon, authenticated;
GRANT SELECT ON public.productos TO anon, authenticated;
GRANT SELECT ON public.vista_locales_mapa TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.locales TO anon, authenticated;
GRANT SELECT, INSERT ON public.locales_productos TO anon, authenticated;
GRANT SELECT, INSERT ON public.verificar_locales TO anon, authenticated;

ALTER TABLE public.locales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.verificar_locales ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Lectura publica locales" ON public.locales;
CREATE POLICY "Lectura publica locales" ON public.locales FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Insercion publica locales" ON public.locales;
CREATE POLICY "Insercion publica locales" ON public.locales FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Actualizacion locales moderacion" ON public.locales;
CREATE POLICY "Actualizacion locales moderacion" ON public.locales FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Audit verificar_locales" ON public.verificar_locales;
CREATE POLICY "Audit verificar_locales" ON public.verificar_locales FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
