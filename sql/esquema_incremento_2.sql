-- 5. TABLA LOCALES (CON CAMPOS NORMALIZADOS)
CREATE TABLE IF NOT EXISTS public.locales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id SMALLINT REFERENCES public.categorias(id) ON DELETE RESTRICT,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    direccion TEXT NOT NULL,
    comuna VARCHAR(50) DEFAULT 'Talca',
    latitud DOUBLE PRECISION NOT NULL,
    longitud DOUBLE PRECISION NOT NULL,
    telefono VARCHAR(30),
    abre TIME,
    cierra TIME,
    metodo_cobro VARCHAR(100) DEFAULT 'Edenred POS',
    estado VARCHAR(30) DEFAULT 'pendiente',
    verificado_por UUID REFERENCES public.usuarios(id) ON DELETE SET NULL,
    ultima_verificacion TIMESTAMPTZ,
    activo BOOLEAN DEFAULT TRUE
